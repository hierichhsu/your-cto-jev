import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { FLOW_DIR, featureIndex, indexStale, renderIndex, writeIndex } from './flow.js';

function repo() {
  const root = mkdtempSync(join(tmpdir(), 'cto-index-'));
  const feature = (slug: string, files: Record<string, string>) => {
    const dir = join(root, FLOW_DIR, 'features', slug);
    mkdirSync(dir, { recursive: true });
    for (const [name, text] of Object.entries(files)) writeFileSync(join(dir, name), text);
  };
  feature('perm', {
    'CONCEPT.md': '# perm\n\nStatus: approved\n\n## 目的\n\n角色與權限。\n',
    'SPEC.md': '# perm\n\nStatus: draft\n',
    'TASKS.md': '- [x] PERM-1 roles (files: src/auth/)\n',
  });
  feature('customers', {
    'CONCEPT.md': '# customers\n\nStatus: approved\n\n## 目的\n\n顧客列表 | 搜尋。\n\n## 動機\n',
    'SPEC.md': '# customers\n\nStatus: approved\n',
    'TASKS.md': [
      '- [ ] CUST-1 list',
      '  - [x] CUST-1.1 api (after: PERM-1) (files: src/customers/api/)',
      '  - [ ] CUST-1.2 ui (after: CUST-1.1, NOPE-9) (files: src/customers/, src/types.ts)',
      '',
    ].join('\n'),
  });
  feature('billing', { 'CONCEPT.md': '# billing\n\n## 目的\n' });
  return root;
}

test('index: rows come from CONCEPT, SPEC and TASKS', () => {
  const rows = featureIndex(repo());
  assert.deepEqual(rows, [
    { slug: 'billing', purpose: '', status: 'planned', code: [], dependsOn: [], signoff: { concept: 'missing', spec: 'missing' } },
    {
      slug: 'customers',
      purpose: '顧客列表 | 搜尋。',
      status: 'active',
      code: ['src/customers/', 'src/types.ts'],
      dependsOn: ['perm'],
      signoff: { concept: 'approved', spec: 'approved' },
    },
    { slug: 'perm', purpose: '角色與權限。', status: 'done', code: ['src/auth/'], dependsOn: [], signoff: { concept: 'approved', spec: 'draft' } },
  ]);
});

test('index: rendered table is deterministic markdown', () => {
  const rows = featureIndex(repo());
  const md = renderIndex([...rows].reverse());
  assert.equal(md, renderIndex(rows), 'row order does not depend on input order');
  assert.ok(md.startsWith('# INDEX\n\n<!-- Generated by cto. Do not edit: run cto index. -->\n'));
  assert.match(md, /Read the row of the feature you work on.*## Interface/);
  assert.match(md, /^\| Feature \| Status \| Purpose \| Code \| Depends on \| Sign-off \|$/m);
  assert.match(md, /^\| customers \| active \| 顧客列表 \\\| 搜尋。 \| src\/customers\/, src\/types\.ts \| perm \| approved\/approved \|$/m);
  assert.match(md, /^\| billing \| planned \|  \|  \|  \| missing\/missing \|$/m);
  assert.ok(md.endsWith('|\n') && !md.includes('\r'), 'LF, trailing newline');
});

test('index: writeIndex writes only on change; indexStale follows TASKS.md edits', () => {
  const root = repo();
  const path = join(root, FLOW_DIR, 'INDEX.md');
  assert.equal(indexStale(root), true, 'missing file while features exist');
  assert.deepEqual(writeIndex(root), { path: `${FLOW_DIR}/INDEX.md`, changed: true });
  assert.equal(readFileSync(path, 'utf8'), renderIndex(featureIndex(root)));
  assert.equal(writeIndex(root).changed, false);
  assert.equal(indexStale(root), false);

  writeFileSync(join(root, FLOW_DIR, 'features', 'perm', 'TASKS.md'), '- [ ] PERM-1 roles (files: src/auth/)\n');
  assert.equal(indexStale(root), true);
  assert.equal(writeIndex(root).changed, true);
  assert.match(readFileSync(path, 'utf8'), /^\| perm \| active \|/m);

  const empty = mkdtempSync(join(tmpdir(), 'cto-index-empty-'));
  assert.deepEqual(writeIndex(empty), { path: `${FLOW_DIR}/INDEX.md`, changed: false });
  assert.equal(indexStale(empty), false);
  assert.equal(existsSync(join(empty, FLOW_DIR)), false, 'no features: nothing created');
});
