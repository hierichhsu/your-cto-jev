import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { PassThrough, Writable } from 'node:stream';
import { test } from 'node:test';
import { loadConfig } from './brain.js';
import { FLOW_RULE, FLOW_SKILL_PATH, FLOW_SKILL_TEXT, RULES_BLOCK, rulesBlock, staleGuidance } from './skill.js';
import { FLOW_SKELETON, docsPublisher, setup } from './setup.js';
import { setupUI } from './setupui.js';

process.env.APPDATA = mkdtempSync(join(tmpdir(), 'cto-home-')); // never touch the user's real keys and prefs

const repo = () => {
  const root = mkdtempSync(join(tmpdir(), 'cto-setup-'));
  execFileSync('git', ['init', '-q'], { cwd: root });
  return root;
};

test('setup --flow: skeleton, skill and rule; idempotent; never overwrites docs; --no-flow keeps the docs; uninstall leaves no trace', () => {
  const root = repo();
  const read = (p: string) => readFileSync(join(root, p), 'utf8');

  const on = setup(root, 'en', { agents: ['claude'], flow: true });
  assert.equal(on.code, 0);
  for (const p of Object.keys(FLOW_SKELETON)) assert.ok(existsSync(join(root, p)), p);
  assert.ok(read('docs/cto_jev/PRODUCT.md').startsWith('# PRODUCT\n\nStatus: draft\n\n## 一句話\n\nunknown\n'));
  assert.match(read('docs/cto_jev/ARCHITECTURE.md'), /^Status: draft$/m);
  assert.match(read('docs/cto_jev/features/platform/SPEC.md'), /^Status: approved$/m);
  assert.match(read('docs/cto_jev/features/platform/CONCEPT.md'), /## 目的\n\nInfrastructure: CI, build, deploy, dependencies/);
  assert.equal(read('docs/cto_jev/features/platform/TASKS.md'), '# platform TASKS\n');
  assert.ok(!existsSync(join(root, 'docs/cto_jev/INDEX.md')), 'INDEX.md is generated by brief, not setup');
  assert.equal(read(FLOW_SKILL_PATH), FLOW_SKILL_TEXT);
  assert.ok(read('CLAUDE.md').includes(FLOW_RULE), 'rules block carries the flow rule');
  assert.ok(read('CLAUDE.md').includes(rulesBlock(true)));
  assert.equal(loadConfig(root).flow, true, 'choice persisted in .cto.json');
  assert.match(on.lines.at(-1)!, /set up PRODUCT\.md and ARCHITECTURE\.md/, 'last line says what to do next');
  assert.deepEqual(staleGuidance(root, ['claude']), [], 'doctor does not flag a flow-on block');

  // the user's edits survive a re-run (what --refresh does: no flow option, saved value applies)
  writeFileSync(join(root, 'docs/cto_jev/PRODUCT.md'), '# PRODUCT\n\nStatus: approved\n\n## 一句話\n\nMy product\n');
  const again = setup(root, 'en', { agents: ['claude'] });
  assert.equal(again.code, 0);
  assert.equal(read('docs/cto_jev/PRODUCT.md'), '# PRODUCT\n\nStatus: approved\n\n## 一句話\n\nMy product\n');
  assert.equal(read('CLAUDE.md').split('YOUR CTO JEV START').length, 2, 'one block');
  assert.ok(read('CLAUDE.md').includes(FLOW_RULE), 'refresh keeps the flow rule');
  assert.ok(!again.lines.some((l) => /set up PRODUCT\.md/.test(l)), 'next-step hint only when the flow was just turned on');
  assert.ok(!again.lines.some((l) => /skeleton/.test(l)), 'nothing created on a re-run');

  // off: skill and rule go, docs stay
  assert.equal(setup(root, 'en', { agents: ['claude'], flow: false }).code, 0);
  assert.ok(!existsSync(join(root, FLOW_SKILL_PATH)));
  assert.ok(!existsSync(join(root, '.agents/skills/cto-flow')));
  assert.ok(existsSync(join(root, '.agents/skills/cto/SKILL.md')), 'the cto skill stays');
  assert.ok(!read('CLAUDE.md').includes(FLOW_RULE));
  assert.ok(read('CLAUDE.md').includes(RULES_BLOCK));
  assert.equal(loadConfig(root).flow, false);
  for (const p of Object.keys(FLOW_SKELETON)) assert.ok(existsSync(join(root, p)), `${p} kept`);

  // uninstall from a flow-on state: no cto-managed file remains; docs and .cto.json are the user's
  setup(root, 'en', { agents: ['claude'], flow: true });
  assert.equal(setup(root, 'en', { uninstall: true }).code, 0);
  assert.ok(!existsSync(join(root, '.agents')));
  assert.ok(!existsSync(join(root, 'CLAUDE.md')));
  assert.ok(!existsSync(join(root, '.claude')));
  assert.ok(existsSync(join(root, 'docs/cto_jev/PRODUCT.md')));
});

test('setup --flow: a docs site generator config gets a reminder to exclude docs/cto_jev/ from publishing', () => {
  const root = repo();
  const run = (flow: boolean) => setup(root, 'en', { agents: ['claude'], flow }).lines.length;
  assert.equal(docsPublisher(root), undefined);
  run(true); // first run creates files; the counts below compare steady-state re-runs only
  const bare = run(true);
  writeFileSync(join(root, 'mkdocs.yml'), 'site_name: x\n');
  assert.equal(docsPublisher(root), 'mkdocs.yml');
  assert.equal(run(true), bare + 1, 'flow on + publisher: exactly one reminder line, on every run');
  run(false); // turning off removes the flow skill (extra lines once); the next off run is steady state
  const off = run(false);
  unlinkSync(join(root, 'mkdocs.yml'));
  assert.equal(run(false), off, 'flow off: no reminder even with the file');
});

// ---------- the flow step in the interactive setup, driven by keystrokes through clack ----------
const KEY = { down: '\x1b[B', enter: '\r', esc: '\x1b' };
async function drive<T>(run: (io: { input: PassThrough; output: Writable }) => Promise<T>, keys: string[]) {
  const input = new PassThrough();
  let out = '';
  const output = new Writable({ write(c, _e, cb) { out += c; cb(); } });
  const p = run({ input, output });
  for (const k of keys) {
    await new Promise((r) => setTimeout(r, 100)); // > clack's 50 ms escape timeout, so a lone Esc is read as Esc
    input.write(k);
  }
  return { result: await p, out };
}

test('setup UI: flow is the last first-run step and an overview item; Esc goes back to the sprint goal', async () => {
  const initial = { agents: [], providers: [], keys: {}, goal: '' };
  const first = await drive((io) => setupUI(initial, true, 'en', { ...io, env: {} }), [
    KEY.enter, // agents: none
    KEY.enter, // providers: none (no keys asked)
    'g', KEY.enter, // sprint goal
    KEY.esc, // flow: Esc goes back to the goal
    KEY.enter, // goal again, kept
    KEY.down, KEY.enter, // flow: yes
    KEY.enter, // overview starts on save
  ]);
  assert.ok(first.result);
  assert.equal(first.result.flow, true);
  assert.equal(first.result.goal, 'g');
  assert.match(first.out, /Use the cto development flow\?/);
  assert.match(first.out, /Development flow/, 'overview row');

  const off = await drive((io) => setupUI({ ...initial, flow: true }, false, 'en', { ...io, env: {} }), [
    KEY.down, KEY.down, KEY.down, KEY.down, KEY.enter, // overview (agents, providers, keys, goal, flow) -> Development flow
    KEY.down, KEY.enter, // cursor starts on the current "yes" (last option); Down wraps to "no"
    KEY.down, KEY.down, KEY.down, KEY.down, KEY.down, KEY.down, KEY.enter, // overview -> save
  ]);
  assert.ok(off.result);
  assert.equal(off.result.flow, false);
});
