test('setup --flow: a docs site generator config gets a reminder to exclude docs/cto_jev/ from publishing', () => {
  const root = repo();
  const run = (flow: boolean) => setup(root, 'en', { agents: ['claude'], flow }).lines.length;
  assert.equal(docsPublisher(root), undefined);
  run(true); // first run creates files; the counts below compare steady-state re-runs only
  const bare = run(true);
  writeFileSync(join(root, 'mkdocs.yml'), 'site_name: x\n');
  assert.equal(docsPublisher(root), 'mkdocs.yml');
  assert.equal(run(true), bare + 1, 'flow on + publisher: exactly one reminder line, on every run');
  run(false); // turning off removes the flow skill (extra lines once); the next off run is steady state
  const off = run(false);
  unlinkSync(join(root, 'mkdocs.yml'));
  assert.equal(run(false), off, 'flow off: no reminder even with the file');
});

// ---------- the flow step in the interactive setup, driven by keystrokes through clack ----------
const KEY = { down: '\x1b[B', right: '\x1b[C', space: ' ', enter: '\r', esc: '\x1b' };
async function drive<T>(run: (io: { input: PassThrough; output: Writable }) => Promise<T>, keys: string[]) {
  const input = new PassThrough();
  let out = '';
  const output = new Writable({ write(c, _e, cb) { out += c; cb(); } });
  const p = run({ input, output });
  for (const k of keys) {
    await new Promise((r) => setTimeout(r, 100)); // > clack's 50 ms escape timeout, so a lone Esc is read as Esc
    input.write(k);
  }
  return { result: await p, out };
}

test('setup UI: flow is the last first-run step and an overview item; no sprint goal is asked', async () => {
  const initial = { agents: [], providers: [], keys: {}, goal: '' };
  const first = await drive((io) => setupUI(initial, true, 'en', { ...io, env: {} }), [
    KEY.enter, // agents: none
    KEY.enter, // providers: none (no keys asked)
    KEY.down, KEY.enter, // flow: yes
    KEY.enter, // overview starts on save
  ]);
  assert.ok(first.result);
  assert.equal(first.result.flow, true);
  assert.equal(first.result.goal, '', 'goal carried through unchanged');
  assert.doesNotMatch(first.out, /sprint goal/i);
  assert.match(first.out, /Use the cto development flow\?/);
  assert.match(first.out, /Development flow/, 'overview row');

  const off = await drive((io) => setupUI({ ...initial, flow: true }, false, 'en', { ...io, env: {} }), [
    KEY.down, KEY.down, KEY.down, KEY.enter, // overview (agents, providers, keys, flow) -> Development flow
    KEY.down, KEY.enter, // cursor starts on the current "yes" (last option); Down wraps to "no"
    KEY.down, KEY.down, KEY.down, KEY.down, KEY.down, KEY.enter, // overview -> save
  ]);
  assert.ok(off.result);
  assert.equal(off.result.flow, false);
});

test('planSetup lists exactly what setup then writes; a second plan after setup is empty; unpicking an agent lists removals', () => {
  const root = repo();
  const plan = planSetup(root, ['claude'], true, '');
  const paths = plan.map((f) => `${f.path}:${f.change}`);
  for (const p of ['.git/hooks/pre-commit:new', '.git/hooks/pre-push:new', '.claude/settings.local.json:new', 'CLAUDE.md:new', '.agents/skills/cto/SKILL.md:new', `${FLOW_SKILL_PATH}:new`, '.claude/commands/cto-jev.md:new', 'docs/cto_jev/PRODUCT.md:new', '.gitignore:new', '.cto.json:new']) {
    assert.ok(paths.includes(p), `${p} in\n${paths.join('\n')}`);
  }
  assert.ok(!paths.some((p) => p.startsWith('AGENTS.md') || p.startsWith('.cursor/')), 'agents not picked are not touched');
  setup(root, 'en', { agents: ['claude'], exact: true, flow: true });
  assert.deepEqual(planSetup(root, ['claude'], true, ''), [], 'nothing left to write after setup ran');
  assert.deepEqual(planSetup(root, [], true, '').map((f) => `${f.path}:${f.change}`).sort(), ['.agents/skills/cto/SKILL.md:remove', '.claude/commands/cto-jev.md:remove', '.claude/settings.local.json:remove', 'CLAUDE.md:remove']);
  assert.deepEqual(planSetup(root, ['claude'], true, 'ship it').map((f) => f.path), ['.cto.json'], 'a new sprint goal only touches .cto.json');
  writeFileSync(join(root, '.claude/settings.local.json'), '{"hooks":{"PreToolUse":{}}}');
  assert.ok(planSetup(root, ['claude'], true, '').some((f) => f.path === '.claude/settings.local.json'), 'a settings file setup would refuse: listed, no crash');
  mkdirSync(join(root, '.claude/skills/cto'), { recursive: true });
  writeFileSync(join(root, '.claude/skills/cto/SKILL.md'), `${SKILL_MARK}\nold`);
  assert.ok(planSetup(root, ['claude'], true, '').some((f) => f.path === '.claude/skills/cto/SKILL.md' && f.change === 'remove'), 'legacy skill removal is listed');
});

test('setup UI: agent list shows what is always installed, each agent\'s files and the picks; the save summary asks before writing', async () => {
  const initial = { agents: ['claude' as const], providers: [], keys: {}, goal: '' };
  const plan = () => [{ path: '.claude/settings.local.json', change: 'new' as const }, { path: 'CLAUDE.md', change: 'update' as const }];
  const r = await drive((io) => setupUI(initial, false, 'en', { ...io, env: {}, detected: ['codex'], plan }), [
    KEY.enter, // overview -> agents
    KEY.down, KEY.down, KEY.down, KEY.space, KEY.enter, // tick Codex CLI
    KEY.down, KEY.down, KEY.down, KEY.down, KEY.down, KEY.enter, // overview -> save
    KEY.right, KEY.enter, // summary: No -> back to the overview
    KEY.down, KEY.down, KEY.down, KEY.down, KEY.down, KEY.enter, // save again
    KEY.enter, // Yes
  ]);
  assert.ok(r.result);
  assert.deepEqual(r.result.agents, ['claude', 'codex']);
  assert.match(r.out, /always installed/);
  assert.match(r.out, /git checks\s+pre-commit, pre-push/);
  assert.match(r.out, /Claude Code\s+\.claude\/settings\.local\.json, CLAUDE\.md/);
  assert.match(r.out, /Codex CLI\s+\.codex\/hooks\.json, AGENTS\.md\s+detected/);
  assert.match(r.out, /Selected: Claude Code, Codex CLI/);
  assert.match(r.out, /Will write/);
  assert.match(r.out, /CLAUDE\.md\s+update cto's part/);
  assert.equal((r.out.match(/Write these files\?/g) ?? []).length >= 2, true, 'asked twice: No went back, Yes saved');
});

test('setup --refresh rewrites an old git hook block in a repo with no agents wired', () => {
  const root = repo();
  assert.equal(isSetUp(root), false);
  setup(root, 'en', { agents: [] });
  assert.equal(isSetUp(root), true);
  const hook = join(root, '.git', 'hooks', 'pre-commit');
  const current = readFileSync(hook, 'utf8');
  const old = current.replace('s=$?; [ $s -eq 0 ] || exit $s\n', ''); // the ≤0.9.8 block
  assert.notEqual(old, current, 'the old block was made');
  writeFileSync(hook, old);
  // hooks shared through a global core.hooksPath: another repo with the block but no .cto.json is not set up
  const other = repo();
  assert.equal(isSetUp(other), false);
  execFileSync('git', ['config', 'core.hooksPath', join(root, '.git', 'hooks')], { cwd: other });
  assert.equal(isSetUp(other), false);
  const cli = join(import.meta.dirname, 'index.js');
  const out = execFileSync(process.execPath, [cli, 'setup', '--refresh'], { cwd: root, encoding: 'utf8', env: { ...process.env, CTO_NO_UPDATE_CHECK: '1' } });
  assert.doesNotMatch(out, /not set up/);
  assert.match(readFileSync(hook, 'utf8'), /s=\$\?; \[ \$s -eq 0 \] \|\| exit \$s/);
});
